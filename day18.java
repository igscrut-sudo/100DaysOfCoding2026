public class day18 {
    public static void main(String[] args) {
        // Tipe data kecil (int berukuran 4 bytes)
        int tipeKecil = 100;
        
        // Konversi otomatis ke tipe data besar (double berukuran 8 bytes)
        double tipeBesar = tipeKecil;
        
        System.out.println("Nilai Integer (Kecil) : " + tipeKecil);
        System.out.println("Nilai Double (Besar)  : " + tipeBesar);
    }
}
